-- إعداد لوحة الإدارة — ملف واحد، يُنفَّذ مرة واحدة (ويمكن إعادة تنفيذه بأمان)
--
-- أين؟  Supabase → SQL Editor → مشروع المنصة (nmukuzolpbkczqayzatp) → الصق الملف كله → Run
--        (هذا هو مشروع قاعدة بيانات الموقع كله والإدارة: انظر js/config.js)
-- بعده: نفّذ 002_add_admin.sql بعد وضع بريدك فيه.
--
-- ماذا يفعل؟
--   1) يضمن أن عمود id في جداول المحتوى (bigint) يولّد أرقامه تلقائيًا (Identity) — حتى تعمل الإضافة من اللوحة.
--   2) ينشئ جدول admin_emails + الدالة is_admin():  المسؤول = بريد مضاف يدويًا + حساب مؤكَّد البريد.
--   3) سياسات RLS: المسؤول فقط يكتب في جداول المحتوى.
--   4) يصلح قراءة جداول «المزيد» للمستخدم المسجَّل: سياساتها الحالية للزائر (anon) فقط، فكان الطالب
--      بعد تسجيل دخوله لا يرى أقسام المزيد ولا المصادر ولا الأوائل ولا جداول الامتحانات. تصير للزائر والمسجَّل.
--   5) يشدّد الصلاحيات: لا كتابة للزائر (anon) في جداول المحتوى، ولا TRUNCATE/TRIGGER/REFERENCES لأحد.
--   6) triggers تحديث updated_at.
--   7) دالتا الاختبارات get_task_questions / submit_task_answer (المنصة تستدعيهما ولم تكن موجودة في هذه القاعدة).
--      ⚠️ كُتبتا من عقد الواجهة (about/js/rooms-api.js و rooms-room.js) لأن نسختهما القديمة غير موجودة في المشروع؛
--         جرّبهما بسؤال تجريبي قبل الاعتماد عليهما.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1) أرقام id التلقائية لجداول bigint (لا يغيّر شيئًا إن كانت تعمل أصلًا)
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t   TEXT;
    nxt BIGINT;
BEGIN
    FOREACH t IN ARRAY ARRAY['subjects', 'material_files', 'additional_resources',
                             'top_years', 'more_items', 'more_contents', 'exam_schedules']
    LOOP
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public' AND table_name = t AND column_name = 'id'
               AND is_identity = 'NO' AND column_default IS NULL
        ) THEN
            EXECUTE format('SELECT COALESCE(MAX(id), 0) + 1 FROM public.%I', t) INTO nxt;
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, nxt);
        END IF;
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 2) المسؤولون: جدول البريد + الدالة
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_emails (
    email      TEXT PRIMARY KEY
               CHECK (email = LOWER(BTRIM(email)) AND POSITION('@' IN email) > 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.admin_emails IS
    'بريد المسؤولين (يُضاف يدويًا من SQL Editor). يجب أن يكون الحساب مؤكَّد البريد في Supabase Auth.';

ALTER TABLE public.admin_emails ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.admin_emails FROM anon, authenticated;
GRANT SELECT ON TABLE public.admin_emails TO authenticated;

-- هل المستخدم الحالي مسؤول؟ SECURITY DEFINER لأنها تقرأ auth.users وadmin_emails المغلقين على الواجهة.
-- تشترط email_confirmed_at: من يسجّل ببريد المسؤول دون تأكيده لا يصبح مسؤولًا.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
          FROM auth.users u
          JOIN public.admin_emails a ON a.email = LOWER(u.email)
         WHERE u.id = auth.uid()
           AND u.email_confirmed_at IS NOT NULL
    );
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;

DROP POLICY IF EXISTS "admin_emails_admin_read" ON public.admin_emails;
CREATE POLICY "admin_emails_admin_read"
    ON public.admin_emails FOR SELECT TO authenticated
    USING ((SELECT public.is_admin()));

-- ---------------------------------------------------------------------
-- 3) سياسات الكتابة للمسؤول على جداول المحتوى
--    (سياسات القراءة العامة الموجودة تبقى كما هي؛ السياسات المتعددة تُجمع بـ OR)
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['subjects', 'material_files', 'additional_resources',
                             'more_items', 'more_contents', 'top_years', 'exam_schedules',
                             'faculty_members', 'community_members',
                             'rooms', 'tasks', 'task_content', 'task_quiz_questions']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "admin_all" ON public.%I', t);
        EXECUTE format(
            'CREATE POLICY "admin_all" ON public.%I FOR ALL TO authenticated '
            'USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()))', t);
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 3-ب) قراءة جداول «المزيد» للزائر والمستخدم المسجَّل معًا
--      (السياسات الأصلية TO anon فقط؛ دور authenticated لا يرث سياسات anon في PostgreSQL)
--      المحتوى عام أصلًا (يراه الزائر)، فلا يتغيّر شيء إلا أن المسجَّل لم يعد يفقد رؤيته.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['additional_resources', 'more_items', 'more_contents',
                             'top_years', 'exam_schedules']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "%s_public_read" ON public.%I', t, t);
        EXECUTE format(
            'CREATE POLICY "%s_public_read" ON public.%I FOR SELECT TO anon, authenticated USING (true)', t, t);
    END LOOP;
END
$$;

-- المسؤول يقرأ إنجازات الطلاب (للإحصائيات فقط — لا كتابة)
DROP POLICY IF EXISTS "admin_read" ON public.user_task_completions;
CREATE POLICY "admin_read"
    ON public.user_task_completions FOR SELECT TO authenticated
    USING ((SELECT public.is_admin()));

-- ---------------------------------------------------------------------
-- 4) تشديد الصلاحيات (Supabase يمنح anon/authenticated كل الصلاحيات افتراضيًا؛ RLS هو الحارس، وهذا خط دفاع ثانٍ)
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['subjects', 'material_files', 'additional_resources',
                             'more_items', 'more_contents', 'top_years', 'exam_schedules',
                             'faculty_members', 'community_members',
                             'rooms', 'tasks', 'task_content', 'task_quiz_questions',
                             'user_task_completions', 'user_task_quiz_answers']
    LOOP
        EXECUTE format('REVOKE TRUNCATE, TRIGGER, REFERENCES ON TABLE public.%I FROM anon, authenticated', t);
        EXECUTE format('REVOKE INSERT, UPDATE, DELETE ON TABLE public.%I FROM anon', t);
    END LOOP;
END
$$;

-- سجلات الإنجاز والإجابات تُكتب فقط عبر دوال SECURITY DEFINER أدناه، لا من المتصفح
REVOKE INSERT, UPDATE, DELETE ON TABLE public.user_task_completions  FROM authenticated;
REVOKE INSERT, UPDATE, DELETE ON TABLE public.user_task_quiz_answers FROM authenticated;

-- ---------------------------------------------------------------------
-- 5) تحديث updated_at تلقائيًا عند التعديل
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    t TEXT;
BEGIN
    -- (جدولا لوحة الطالب: قاعدة المنصة الجديدة أُنشئت بلا triggers، فتُستعاد هنا ليتحدّث updated_at عند الحفظ)
    FOREACH t IN ARRAY ARRAY['subjects', 'faculty_members', 'rooms', 'tasks', 'task_content',
                             'student_dashboard_profiles', 'student_dashboard_progress']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS "admin_set_updated_at" ON public.%I', t);
        EXECUTE format(
            'CREATE TRIGGER "admin_set_updated_at" BEFORE UPDATE ON public.%I '
            'FOR EACH ROW EXECUTE FUNCTION public.admin_set_updated_at()', t);
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- 6) دوال الاختبارات (الإجابة الصحيحة لا تغادر الخادم)
-- ---------------------------------------------------------------------

-- أسئلة مهمة منشورة: id + السؤال + الاختيارات (بدون الإجابة الصحيحة) + هل أجاب عنه المستخدم
CREATE OR REPLACE FUNCTION public.get_task_questions(p_task_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_uid UUID := auth.uid();
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '28000';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM public.tasks t
          JOIN public.rooms r ON r.id = t.room_id
         WHERE t.id = p_task_id AND t.is_active AND r.is_active
    ) THEN
        RAISE EXCEPTION 'TASK_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    RETURN COALESCE((
        SELECT JSONB_AGG(
                   JSONB_BUILD_OBJECT(
                       'id',       q.id,
                       'question', q.question,
                       'options',  q.options,
                       'answered', EXISTS (
                           SELECT 1 FROM public.user_task_quiz_answers a
                            WHERE a.user_id = v_uid AND a.question_id = q.id)
                   )
                   ORDER BY q.sort_order, q.created_at
               )
          FROM public.task_quiz_questions q
         WHERE q.task_id = p_task_id AND q.is_active
    ), '[]'::JSONB);
END;
$$;

REVOKE ALL ON FUNCTION public.get_task_questions(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_task_questions(UUID) TO authenticated;

-- التحقق من إجابة: الصحيحة تُسجَّل، وبإجابة كل أسئلة المهمة يُسجَّل إنجازها مرة واحدة بنقاطها.
CREATE OR REPLACE FUNCTION public.submit_task_answer(p_question_id UUID, p_option_id TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_uid       UUID := auth.uid();
    v_task_id   UUID;
    v_correct_id TEXT;
    v_is_correct BOOLEAN;
    v_total     INTEGER;
    v_answered  INTEGER;
    v_points    INTEGER;
    v_row       public.user_task_completions%ROWTYPE;
    v_completed BOOLEAN := FALSE;
    v_new       BOOLEAN := FALSE;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '28000';
    END IF;

    SELECT q.task_id, q.correct_option_id
      INTO v_task_id, v_correct_id
      FROM public.task_quiz_questions q
      JOIN public.tasks t ON t.id = q.task_id
      JOIN public.rooms r ON r.id = t.room_id
     WHERE q.id = p_question_id AND q.is_active AND t.is_active AND r.is_active;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'QUESTION_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    v_is_correct := (p_option_id IS NOT NULL AND p_option_id = v_correct_id);

    IF v_is_correct THEN
        INSERT INTO public.user_task_quiz_answers (user_id, question_id)
        VALUES (v_uid, p_question_id)
        ON CONFLICT ON CONSTRAINT user_task_quiz_answers_user_question_key DO NOTHING;
    END IF;

    SELECT COUNT(*) INTO v_total
      FROM public.task_quiz_questions q
     WHERE q.task_id = v_task_id AND q.is_active;

    SELECT COUNT(*) INTO v_answered
      FROM public.user_task_quiz_answers a
      JOIN public.task_quiz_questions q ON q.id = a.question_id
     WHERE a.user_id = v_uid AND q.task_id = v_task_id AND q.is_active;

    IF v_total > 0 AND v_answered >= v_total THEN
        v_completed := TRUE;

        SELECT t.points INTO v_points FROM public.tasks t WHERE t.id = v_task_id;

        INSERT INTO public.user_task_completions (user_id, task_id, awarded_points)
        VALUES (v_uid, v_task_id, v_points)
        ON CONFLICT ON CONSTRAINT user_task_completions_user_task_key DO NOTHING
        RETURNING * INTO v_row;

        IF FOUND THEN
            v_new := TRUE;
        ELSE
            SELECT * INTO v_row
              FROM public.user_task_completions c
             WHERE c.user_id = v_uid AND c.task_id = v_task_id;
        END IF;
    END IF;

    RETURN JSONB_BUILD_OBJECT(
        'correct',            v_is_correct,
        'completed',          v_completed,
        'newly_completed',    v_new,
        'awarded_points',     COALESCE(v_row.awarded_points, 0),
        'answered_questions', v_answered,
        'total_questions',    v_total,
        'completed_at',       v_row.completed_at
    );
END;
$$;

REVOKE ALL ON FUNCTION public.submit_task_answer(UUID, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_task_answer(UUID, TEXT) TO authenticated;

COMMIT;

